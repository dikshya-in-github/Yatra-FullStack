    /**
     * Creates the demo dataset — airlines, airports, accounts, flights, bookings,
     * payments and tickets, in one transaction.
     *
     * @throws ConflictException 409 {@code ALREADY_SEEDED} — the marker is already
     *                           present; reset first
     */
    @Transactional
    public SeedResponse seed() {
        requireNotSeeded();

        LocalDate today = LocalDate.now();
        LocalDateTime now = LocalDateTime.now();

        int destinationsCreated = seedDestinations();
        Map<String, Airline> airlinesByIata = seedAirlines();
        Map<String, User> usersByEmail = seedUsers(now);
        Map<String, Flight> flightsByNo = seedFlights(airlinesByIata, today);
        Map<String, Integer> bookingCounts = seedBookings(flightsByNo, usersByEmail, now);

        Map<String, Integer> counts = new LinkedHashMap<>();
        counts.put("airlines", airlinesByIata.size());
        // "In place", not "inserted": a destination or carrier that already existed (a
        // re-seed, or an airport the admin added) still counts, because what the counts
        // describe is the dataset the seed guarantees, not how much work it had to do.
        // Otherwise a second seed after a reset — where the airports were deliberately
        // kept — would report zero destinations that it had just finished using.
        counts.put("destinations", DESTINATIONS.size());
        counts.put("users", usersByEmail.size());
        counts.put("flights", flightsByNo.size());
        counts.put("seats", flightsByNo.values().stream().mapToInt(Flight::getSeatCapacity).sum());
        counts.put("bookings", bookingCounts.get("bookings"));
        counts.put("passengers", bookingCounts.get("passengers"));
        counts.put("payments", bookingCounts.get("bookings"));
        counts.put("tickets", bookingCounts.get("bookings"));

        log.info("Demo seed applied: {} airlines, {} destinations ({} created), {} users, {} flights, {} bookings",
                counts.get("airlines"), counts.get("destinations"), destinationsCreated,
                counts.get("users"), counts.get("flights"), counts.get("bookings"));

        return new SeedResponse(
                "SEED",
                "Demo data created. Admin sign-in: admin@gmail.com (password: the documented admin credential). "
                        + "Destinations are left un-marked, so a reset keeps them.",
                counts,
                List.of());
    }

    /**
     * Refuses a second seed. Guarded by the marker, not by a count of flights, so it
     * stays correct once the demo's own numbers have moved on.
     */
    private void requireNotSeeded() {
        boolean alreadySeeded = !airlines.findBySeededTrue().isEmpty()
                || !flights.findBySeededTrue().isEmpty()
                || !users.findBySeededTrue().isEmpty()
                || !bookings.findBySeededTrue().isEmpty();

        if (alreadySeeded) {
            throw new ConflictException("ALREADY_SEEDED",
                    "The demo data is already seeded. Call POST /api/admin/reset first — seeding twice would "
                            + "double every flight's booked seats and mint a second payment and ticket per "
                            + "booking, which the unique keys on the booking row would then refuse anyway.");
        }
    }

    /**
     * Airports — find-or-create by code, so a destination the admin already added (or
     * a partial earlier run) does not collide with the {@code code} unique key.
     * Destinations carry no seed marker on purpose: see the class docs.
     */
    private int seedDestinations() {
        int created = 0;
        for (DestinationSeed seed : DESTINATIONS) {
            if (destinations.findByCode(seed.code()).isPresent()) {
                continue;
            }
            Destination destination = new Destination();
            destination.setCity(seed.city());
            destination.setCode(seed.code());
            destination.setAirport(seed.airport());
            destination.setDescription(seed.description());
            destination.setStatus(ACTIVE);
            destinations.save(destination);
            created++;
        }
        destinations.flush();
        return created;
    }

    /** Carriers, through the airline service — so the IATA uniqueness rule and the logo write both apply. */
    private Map<String, Airline> seedAirlines() {
        Map<String, Airline> byIata = new LinkedHashMap<>();

        for (AirlineSeed seed : AIRLINES) {
            Optional<Airline> existing = airlines.findByIata(seed.iata());
            if (existing.isPresent()) {
                // A hand-made carrier already owns this code: use it, do not mark it as
                // seed data, and do not overwrite it. Its flights still seed fine.
                byIata.put(seed.iata(), existing.get());
                continue;
            }

            Airline airline = airlineService.createAirline(new AirlineRequest(
                    seed.name(), seed.iata(), seed.description(), ACTIVE, logoDataUrl(seed.logoFile())));
            airline.setSeeded(true);
            byIata.put(seed.iata(), airline);
        }

        airlines.flush();
        return byIata;
    }

    /**
     * The account roster, with BCrypt hashes of the documented demo credential —
     * {@link #ADMIN_PASSWORD} for the administrator, {@link #DEMO_PASSWORD} for the rest.
     *
     * <p>Email is lower-cased before the lookup because {@code users.email} is
     * {@code utf8mb4_bin} and {@code UserService} lower-cases on registration —
     * matching its rule keeps the two paths agreeing on what "the same email" means.
     */
    private Map<String, User> seedUsers(LocalDateTime now) {
        Map<String, User> byEmail = new LinkedHashMap<>();
        String hash = passwordEncoder.encode(DEMO_PASSWORD);
        String adminHash = passwordEncoder.encode(ADMIN_PASSWORD);

        for (UserSeed seed : USERS) {
            String email = seed.email().toLowerCase(Locale.ROOT);
            Optional<User> existing = users.findByEmailIgnoreCase(email);
            if (existing.isPresent()) {
                byEmail.put(email, existing.get());
                continue;
            }

            User user = new User();
            user.setName(seed.name());
            user.setEmail(email);
            user.setPhone(seed.phone());
            /* The administrator is the one account with its own password (see
               ADMIN_PASSWORD) — every other seeded row shares DEMO_PASSWORD. */
            user.setPassword("ADMIN".equals(seed.role()) ? adminHash : hash);
            user.setRole(seed.role());
            user.setStatus(seed.status());
            user.setRegisteredAt(now.minusDays(seed.daysAgo()));
            user.setSeeded(true);
            users.save(user);
            byEmail.put(email, user);
        }

        users.flush();
        return byEmail;
    }

    /**
     * The flight list — through {@link FlightService#createFlight}, so each flight gets
     * its generated seat map from the one implementation that owns that rule.
     *
     * <p>{@code date} is set here (unlike the admin form, which has no date input): a
     * seeded flight should be findable by a date-filtered search, and the dates are
     * relative to today so the demo never goes stale.
     */
    private Map<String, Flight> seedFlights(Map<String, Airline> airlinesByIata, LocalDate today) {
        Map<String, Flight> byNo = new LinkedHashMap<>();

        for (FlightSeed seed : FLIGHTS) {
            Airline airline = airlinesByIata.get(seed.iata());
            if (airline == null) {
                throw new IllegalStateException(
                        "seed flight " + seed.no() + " names an airline that was not seeded: " + seed.iata());
            }

            Flight flight = flightService.createFlight(new FlightRequest(
                    seed.no(), airline.getId(), seed.from(), seed.to(),
                    today.plusDays(seed.daysFromToday()),
                    LocalTime.parse(seed.dep()), LocalTime.parse(seed.arr()), seed.aircraft(),
                    new BigDecimal(seed.fare()), seed.seats(), ACTIVE));
            flight.setSeeded(true);
            byNo.put(seed.no(), flight);
        }

        flights.flush();
        return byNo;
    }

    /**
     * The bookings, with their payment and ticket rows.
     *
     * <p>Each one is created by {@link BookingService#createBooking} — contact block,
     * passengers, and the seats they hold — and then moved to its seeded status. That
     * ordering matters: the seat claim is the same atomic UPDATE a customer's booking
     * goes through, so a seeded flight's {@code bookedSeats} is real from the first
     * second, and the mock's invented counts are no longer anywhere in the picture.
     *
     * <p>The cancelled/refunded booking keeps its seats, exactly as the admin page's
     * own cancel dialog promises ("Seats stay counted on the flight; the refund itself
     * is completed by the payments flow").
     */
    private Map<String, Integer> seedBookings(Map<String, Flight> flightsByNo,
                                              Map<String, User> usersByEmail,
                                              LocalDateTime now) {
        int passengerCount = 0;

        for (int index = 0; index < BOOKINGS.size(); index++) {
            BookingSeed seed = BOOKINGS.get(index);
            Flight flight = flightsByNo.get(BOOKING_FLIGHTS.get(index));
            if (flight == null) {
                throw new IllegalStateException("seed booking " + seed.pnr() + " names an unseeded flight");
            }

            User user = usersByEmail.get(seed.email().toLowerCase(Locale.ROOT));
            LocalDateTime createdAt = now.minusDays(seed.daysAgo()).withNano(0);

            Booking booking = bookingService.createBooking(
                    bookingRequest(seed, flight, createdAt), user == null ? null : user.getId());

            booking.setBookingStatus(seed.status());
            booking.setPaymentStatus(seed.paymentStatus());
            booking.setFareClass(seed.fareClass());
            booking.setRefundable(seed.refundable());
            booking.setCreatedAt(createdAt);
            booking.setSeeded(true);
            bookings.save(booking);

            payments.save(payment(booking, seed, createdAt));
            tickets.save(ticket(booking, seed, createdAt));
            passengerCount += seed.passengers().size();
        }

        bookings.flush();
        payments.flush();
        tickets.flush();

        Map<String, Integer> counts = new HashMap<>();
        counts.put("bookings", BOOKINGS.size());
        counts.put("passengers", passengerCount);
        return counts;
    }

    /**
     * The wizard's payload shape, built from a seed record — so a seeded booking
     * travels the exact request path {@code booking.js} uses. The pricing fields are
     * left null on purpose: {@code BookingService} ignores whatever the client sends
     * and computes the total from the flight row.
     */
    private BookingRequest bookingRequest(BookingSeed seed, Flight flight, LocalDateTime createdAt) {
        List<BookingRequest.Passenger> rows = new ArrayList<>();
        for (PassengerSeed passenger : seed.passengers()) {
            rows.add(new BookingRequest.Passenger(passenger.title(), passenger.firstName(), null,
                    passenger.lastName(), "Nepali", passenger.type(), null));
        }

        BookingRequest.Contact contact = new BookingRequest.Contact(
                seed.passengers().get(0).title(),
                seed.passengers().get(0).firstName(),
                null,
                seed.passengers().get(0).lastName(),
                seed.email(), contactPhone(seed.email()), "Self", "", true);

        BookingRequest.SelectedFlight selected = new BookingRequest.SelectedFlight(
                flight.getFlightNo(),
                flight.getOrigin() == null ? null : flight.getOrigin().getCode(),
                flight.getDestination() == null ? null : flight.getDestination().getCode(),
                flight.getFlightDate() == null ? null : flight.getFlightDate().toString(),
                null, null, null, seed.fareClass(), seed.refundable(), null, rows.size(), null);

        return new BookingRequest(contact, rows, selected, null);
    }

    /** The eSewa row the mock pairs with each booking; the amount must equal the booking's. */
    private Payment payment(Booking booking, BookingSeed seed, LocalDateTime createdAt) {
        Payment payment = new Payment();
        payment.setBooking(booking);
        payment.setMethod("eSewa");
        payment.setTxnId(seed.txnId());
        payment.setAmount(booking.getTotalAmount());
        payment.setStatus(REFUNDED.equalsIgnoreCase(seed.paymentStatus()) ? "REFUNDED" : SUCCESS);
        payment.setCreatedAt(createdAt);
        payment.setPaidAt(createdAt.plusMinutes(7));
        return payment;
    }

    /** A refunded booking's ticket is CANCELLED rather than ISSUED — the shape a refund leaves behind. */
    private Ticket ticket(Booking booking, BookingSeed seed, LocalDateTime createdAt) {
        Ticket ticket = new Ticket();
        ticket.setBooking(booking);
        ticket.setPnr(seed.pnr());
        ticket.setTicketNo(seed.ticketNo());
        ticket.setStatus(REFUNDED.equalsIgnoreCase(seed.paymentStatus()) ? CANCELLED : "ISSUED");
        ticket.setIssuedAt(createdAt.plusMinutes(8));
        return ticket;
    }

    /* ------------------------------------------------------------------ *
     *  Reset                                                              *
     * ------------------------------------------------------------------ */

    /**
     * Removes every row carrying the seed marker, in foreign-key order, and reports
     * what it kept.
     *
     * <p>This is the one place that hard-deletes a paid, ticketed booking. That is
     * deliberate and it is not a hole in R4's rule: the rule governs the admin APIs
     * (where a sale record is cancelled, never deleted), while a reset is a separate
     * demo-data operation that only ever touches rows this seeder created. The
     * alternative the standards doc rejected was relaxing the delete endpoint itself.
     *
     * <p>Deletion order follows the R4 probe: passengers, payments and tickets first
     * (with a flush), then the booking rows — because a deleted parent with a managed
     * child still pointing at it trips Hibernate's transient-reference check even with
     * {@code cascade = ALL} on the collection.
     */
    @Transactional
    public SeedResponse reset() {
        Map<String, Integer> counts = new LinkedHashMap<>();
        List<String> kept = new ArrayList<>();

        int[] bookingRows = deleteSeededBookings();
        Map<String, Integer> flightRows = deleteSeededFlights();
        int usersDeleted = deleteSeededUsers(kept);
        int airlinesDeleted = deleteSeededAirlines(kept);

        counts.put("airlines", airlinesDeleted);
        counts.put("destinations", 0);
        counts.put("users", usersDeleted);
        counts.put("flights", flightRows.get("flights"));
        counts.put("seats", flightRows.get("seats"));
        counts.put("bookings", bookingRows[0]);
        counts.put("passengers", bookingRows[1]);
        counts.put("payments", bookingRows[2]);
        counts.put("tickets", bookingRows[3]);

        log.info("Demo seed reset: {} bookings, {} flights, {} users, {} airlines removed",
                counts.get("bookings"), counts.get("flights"), counts.get("users"), counts.get("airlines"));

        return new SeedResponse(
                "RESET",
                kept.isEmpty()
                        ? "Seed data removed. Destinations were kept — airports are reference data, not demo data."
                        : "Seed data removed. Some seeded rows were kept because your own records still use them — "
                          + "see `kept`. Destinations were kept as reference data.",
                counts,
                kept);
    }

    /** @return {@code [bookings, passengers, payments, tickets]} deleted */
    private int[] deleteSeededBookings() {
        List<Booking> seeded = bookings.findBySeededTrue();
        int passengerCount = 0;
        int paymentCount = 0;
        int ticketCount = 0;

        for (Booking booking : seeded) {
            List<Passenger> rows = passengers.findByBookingId(booking.getId());
            passengerCount += rows.size();
            passengers.deleteAll(rows);

            Optional<Payment> payment = payments.findByBookingId(booking.getId());
            if (payment.isPresent()) {
                payments.delete(payment.get());
                paymentCount++;
            }

            Optional<Ticket> ticket = tickets.findByBookingId(booking.getId());
            if (ticket.isPresent()) {
                tickets.delete(ticket.get());
                ticketCount++;
            }
        }

        passengers.flush();
        payments.flush();
        tickets.flush();
        bookings.deleteAll(seeded);
        bookings.flush();

        return new int[]{seeded.size(), passengerCount, paymentCount, ticketCount};
    }

    /** @return {@code {flights, seats}} deleted — the seat map goes before its flight */
    private Map<String, Integer> deleteSeededFlights() {
        List<Flight> seeded = flights.findBySeededTrue();
        int seatRows = 0;

        for (Flight flight : seeded) {
            List<Seat> map = seats.findByFlightId(flight.getId());
            seatRows += map.size();
            seats.deleteAll(map);
        }

        seats.flush();
        flights.deleteAll(seeded);
        flights.flush();

        Map<String, Integer> counts = new HashMap<>();
        counts.put("flights", seeded.size());
        counts.put("seats", seatRows);
        return counts;
    }

    /**
     * Deletes the seeded accounts, except any that still owns a booking you made —
     * deleting one would take that booking with it through the {@code user_id} FK.
     */
    private int deleteSeededUsers(List<String> kept) {
        List<User> removable = new ArrayList<>();

        for (User user : users.findBySeededTrue()) {
            long ownBookings = bookings.countByUserId(user.getId());
            if (ownBookings > 0) {
                kept.add(user.getEmail() + " (seeded account kept — " + ownBookings
                        + " booking(s) of your own still reference it)");
            } else {
                removable.add(user);
            }
        }

        users.deleteAll(removable);
        users.flush();
        return removable.size();
    }

    /**
     * Same rule for carriers: one your own flight still uses stays, with the reason
     * reported — and it <b>keeps its marker</b>. That is deliberate: the row is still
     * seed data, it simply could not be removed yet, so the next reset will remove it
     * once the last record of yours using it is gone. Clearing the flag here would
     * quietly promote it to permanent fixture and a reset could never reach it again.
     */
    private int deleteSeededAirlines(List<String> kept) {
        List<Airline> removable = new ArrayList<>();

        for (Airline airline : airlines.findBySeededTrue()) {
            long remaining = flights.countByAirlineId(airline.getId());
            if (remaining > 0) {
                kept.add(airline.getName() + " (seeded airline kept — " + remaining
                        + " flight(s) of your own still use it)");
            } else {
                removable.add(airline);
            }
        }

        airlines.deleteAll(removable);
        airlines.flush();
        return removable.size();
    }

