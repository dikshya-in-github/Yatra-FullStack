/**
 * Roadmap Phase 7 — the demo data seeder, and the reset that makes it re-runnable.
 *
 * <h2>What it writes, and where the numbers come from</h2>
 *
 * <p><b>The frontend mock is the source of the content, not this class's
 * imagination.</b> The four carriers, the eleven airports, the ten-account roster,
 * the flight numbers/routes/fares and the eight bookings with their PNRs, ticket
 * numbers and eSewa transaction ids are all transcribed from
 * {@code assets/js/mock-data.js}, {@code admin-flights.js} and
 * {@code admin-bookings.js}. The pages already render those exact records in mock
 * mode, so a seeded database answers the real API with data those pages recognise —
 * which is the same "the frontend is the contract" call the airline, flight and
 * booking modules made. Six extra flights are added on top of the mock's six so the
 * admin table's pagination is visibly exercised rather than theoretical.
 *
 * <p><b>It reuses the real services rather than inserting rows.</b> Airlines go
 * through {@link AirlineService#createAirline} (so the IATA rules and the R8 logo
 * write apply), flights through {@link FlightService#createFlight} (so the seat map
 * is generated by the one piece of code that knows how to generate it), and bookings
 * through {@link BookingService#createBooking} (so the seeded bookings hold their
 * seats through the same atomic claim a customer's booking uses). If any of those
 * paths breaks, seeding fails loudly — which is the point: a seeder that bypasses the
 * services would happily manufacture data the API itself would reject.
 *
 * <h2>Re-runnable, and honest about how</h2>
 *
 * <p>{@link #seed()} is <b>not</b> additive on top of the last seed: it refuses with
 * 409 {@code ALREADY_SEEDED} when the marker is already present, because seeding
 * twice would double every flight's booked seats and mint a second set of payments
 * and tickets (both {@code unique NOT NULL} on {@code booking_id}). The re-run path is
 * therefore explicit: {@link #reset()} then {@link #seed()}.
 *
 * <p>That is exactly the operation the standards doc left open in §7 question 6 —
 * whether seeded bookings may vanish completely. R4's rule is untouched: a paid,
 * ticketed booking is still a sale record and the admin APIs still answer 409 and say
 * "cancel it instead". A <b>reset</b> is the separate, deliberately destructive
 * operation that removes rows carrying the seed marker, and only those.
 *
 * <h2>Why the marker column exists</h2>
 *
 * <p>Every row this class creates carries {@code seeded = true} (see
 * {@code Model/Airline} for the marker's own note). Without it a reset would have to
 * guess from natural keys — and deleting "everything whose flight number is U4 951"
 * would take an admin's own flight with it if they happened to type that number.
 * The marker is also what the mock already models: its demo bookings carry
 * {@code _seed: true}, and that flag is what makes the mock's trash icon appear on
 * demo rows only.
 *
 * <h2>What a reset deliberately keeps</h2>
 *
 * <ul>
 *   <li><b>Destinations.</b> Airports are reference data the whole app needs, not
 *       demo content; a reset that deleted them would break every hand-made flight's
 *       route and the wizard's airport lookup.</li>
 *   <li><b>A seeded airline or user that your own rows still reference.</b> Reported
 *       in {@link SeedResponse#kept()} with the reason, and left in place — a reset
 *       removes the demo data, not your work.</li>
 * </ul>
 */
