    /**
     * The airline logo read from the served assets and handed to the airline service as
     * a data URL — the one form its write path accepts (R8).
     *
     * <p>The files are the mock's own logo paths, so a seeded carrier renders exactly
     * what mock mode renders, and the bytes really do land in the {@code logo}
     * MEDIUMBLOB — the assignment's "images in the database" criterion, demonstrated
     * rather than just implemented.
     *
     * <p>Failures are tolerated: a missing or unreadable asset logs a warning and seeds
     * the airline without a logo, because demo data with one missing image is better
     * than a seed that cannot run.
     */
    private String logoDataUrl(String fileName) {
        try (InputStream stream = resource(fileName).getInputStream()) {
            byte[] bytes = stream.readAllBytes();
            return "data:" + contentType(fileName) + ";base64," + Base64.getEncoder().encodeToString(bytes);
        } catch (IOException | RuntimeException ex) {
            log.warn("Seed: could not read airline logo {} — seeding that airline without one ({})",
                    fileName, ex.getMessage());
            return null;
        }
    }

    private Resource resource(String fileName) {
        return new ClassPathResource("static/assets/imgs/" + fileName);
    }

    private static String contentType(String fileName) {
        String lower = fileName.toLowerCase(Locale.ROOT);
        if (lower.endsWith(".svg")) {
            return "image/svg+xml";
        }
        if (lower.endsWith(".png")) {
            return "image/png";
        }
        if (lower.endsWith(".jpg") || lower.endsWith(".jpeg")) {
            return "image/jpeg";
        }
        return "application/octet-stream";
    }

    /**
     * The seeded accounts' mobile numbers, mirrored from the mock's roster — the booking
     * needs a contact number and using the owner's own keeps the two views consistent.
     */
    private static String contactPhone(String email) {
        return USERS.stream()
                .filter(user -> user.email().equalsIgnoreCase(email))
                .map(UserSeed::phone)
                .findFirst()
                .orElse("9800000000");
    }
